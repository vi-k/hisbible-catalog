  static List<BookInfo> get all => _books;

  /// Приводит старый номер книги к нынешнему; прочие номера не меняет.
  static int normalize(int number) => _legacyNumbers[number] ?? number;

  /// Книга по номеру (старые номера приводятся к нынешним) или `null`.
  static BookInfo? byNumber(int number) => _byNumber[normalize(number)];

  /// Книга по коду SIL или `null`.
  static BookInfo? bySilCode(String code) => _bySilCode[code];

  /// Код книги в файлах HisBible: код SIL или `H<номер>` для книги без кода.
  static String codeOf(int number) => byNumber(number)?.silCode ?? 'H$number';

  /// Номер книги по коду из [codeOf] или `null`, если код не распознан.
  ///
  /// Код `H<номер>` годится только для книги без кода SIL: у книги с кодом
  /// единственный код — её код SIL. Номер, который не помещается в `int`,
  /// — тоже `null`.
  static int? numberOfCode(String code) {
    final known = bySilCode(code);
    if (known != null) {
      return known.number;
    }
    final match = _numericCode.firstMatch(code);
    if (match == null) {
      return null;
    }
    final number = int.tryParse(match[1]!);
    if (number == null) {
      return null;
    }

    return byNumber(number)?.silCode == null ? number : null;
  }

